create table if not exists public.restaurant_reservations (
    id bigint generated by default as identity primary key,
    restaurant_id uuid not null references public.restaurants(id) on delete cascade,
    customer_user_id uuid not null references auth.users(id) on delete cascade,
    customer_name text not null check (char_length(btrim(customer_name)) between 2 and 100),
    customer_phone text not null check (char_length(btrim(customer_phone)) between 5 and 30),
    reservation_at timestamptz not null,
    party_size integer not null check (party_size between 1 and 20),
    customer_note text not null default '' check (char_length(customer_note) <= 500),
    status text not null default 'pending' check (status in ('pending', 'confirmed', 'rejected', 'cancelled')),
    owner_note text not null default '' check (char_length(owner_note) <= 500),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint restaurant_reservations_id_restaurant_unique unique (id, restaurant_id)
);
create index if not exists restaurant_reservations_tenant_time_idx on public.restaurant_reservations (restaurant_id, reservation_at desc);
create index if not exists restaurant_reservations_customer_time_idx on public.restaurant_reservations (customer_user_id, reservation_at desc);
alter table public.restaurant_reservations enable row level security;
drop policy if exists "Customers and owners can read tenant reservations" on public.restaurant_reservations;
create policy "Customers and owners can read tenant reservations" on public.restaurant_reservations for select to authenticated
using (customer_user_id = (select auth.uid()) or private.is_restaurant_owner(restaurant_id));
revoke all on public.restaurant_reservations from anon, authenticated;
grant select on public.restaurant_reservations to authenticated;
grant usage, select on sequence public.restaurant_reservations_id_seq to authenticated;

create or replace function public.create_restaurant_reservation(
    p_restaurant_id uuid, p_customer_name text, p_customer_phone text,
    p_reservation_at timestamptz, p_party_size integer, p_customer_note text default ''
)
returns table(reservation_id bigint, reservation_status text)
language plpgsql security definer set search_path = ''
as $function$
declare v_user_id uuid := auth.uid(); v_reservation_id bigint;
begin
    if v_user_id is null then raise exception 'يجب تسجيل الدخول قبل إرسال طلب الحجز.'; end if;
    if p_restaurant_id is null or not exists (
        select 1 from public.restaurants r join public.customer_restaurants cr on cr.restaurant_id = r.id
        where r.id = p_restaurant_id and r.status = 'active' and cr.user_id = v_user_id
    ) then raise exception 'هذا المطعم غير مرتبط بحسابك أو غير نشط.'; end if;
    if p_reservation_at is null or p_reservation_at <= now() then raise exception 'اختر موعداً مستقبلياً للحجز.'; end if;
    if p_party_size is null or p_party_size not between 1 and 20 then raise exception 'عدد الأشخاص يجب أن يكون بين 1 و20.'; end if;
    if char_length(btrim(coalesce(p_customer_name, ''))) not between 2 and 100 then raise exception 'أدخل اسماً صحيحاً.'; end if;
    if char_length(btrim(coalesce(p_customer_phone, ''))) not between 5 and 30 then raise exception 'أدخل رقم هاتف صحيحاً.'; end if;
    if char_length(coalesce(p_customer_note, '')) > 500 then raise exception 'الملاحظة طويلة جداً.'; end if;
    insert into public.restaurant_reservations (restaurant_id, customer_user_id, customer_name, customer_phone, reservation_at, party_size, customer_note)
    values (p_restaurant_id, v_user_id, btrim(p_customer_name), btrim(p_customer_phone), p_reservation_at, p_party_size, btrim(coalesce(p_customer_note, '')))
    returning id into v_reservation_id;
    return query select v_reservation_id, 'pending'::text;
end;
$function$;

create or replace function public.update_restaurant_reservation_status(
    p_reservation_id bigint, p_restaurant_id uuid, p_status text, p_owner_note text default ''
)
returns boolean language plpgsql security definer set search_path = ''
as $function$
begin
    if not private.is_restaurant_owner(p_restaurant_id) then raise exception 'ليس لديك صلاحية إدارة حجوزات هذا المطعم.'; end if;
    if p_status not in ('confirmed', 'rejected') then raise exception 'حالة الحجز غير صالحة.'; end if;
    if char_length(coalesce(p_owner_note, '')) > 500 then raise exception 'ملاحظة المالك طويلة جداً.'; end if;
    update public.restaurant_reservations set status = p_status, owner_note = btrim(coalesce(p_owner_note, '')), updated_at = now()
    where id = p_reservation_id and restaurant_id = p_restaurant_id and status = 'pending';
    return found;
end;
$function$;
revoke all on function public.create_restaurant_reservation(uuid,text,text,timestamptz,integer,text) from public;
grant execute on function public.create_restaurant_reservation(uuid,text,text,timestamptz,integer,text) to authenticated;
revoke all on function public.update_restaurant_reservation_status(bigint,uuid,text,text) from public;
grant execute on function public.update_restaurant_reservation_status(bigint,uuid,text,text) to authenticated;
